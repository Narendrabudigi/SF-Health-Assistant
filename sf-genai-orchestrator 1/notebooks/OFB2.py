# 22. TREND STATISTICS — MANN-KENDALL + SEN'S SLOPE
# ============================================================
import math
import numpy as np # Ensure np is available

def mann_kendall_sen(values):
    y = pd.Series(values).dropna().astype(float).to_numpy()
    n = len(y)

    if n < 3:
        return {
            "n": n,
            "direction": "Insufficient data",
            "statistic": np.nan,
            "p_value": np.nan,
            "sen_slope": np.nan
        }

    S = 0
    slopes = []

    for i in range(n - 1):
        for j in range(i + 1, n):
            S += np.sign(y[j] - y[i])
            slopes.append((y[j] - y[i]) / (j - i))

    varS = n * (n - 1) * (2 * n + 5) / 18

    if S > 0:
        z = (S - 1) / np.sqrt(varS)
    elif S < 0:
        z = (S + 1) / np.sqrt(varS)
    else:
        z = 0

    p = math.erfc(abs(z) / np.sqrt(2))
    slope = float(np.median(slopes)) if slopes else np.nan

    direction = (
        "Increasing" if slope > 0
        else "Decreasing" if slope < 0
        else "No trend"
    )

    return {
        "n": n,
        "direction": direction,
        "statistic": S,
        "p_value": p,
        "sen_slope": slope
    }

