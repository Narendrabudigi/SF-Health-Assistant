def add_offboarding_date_features(
    data,
    start_col="offboardingStartDate",
    lwd_col="lastWorkingDate",
    kt_scheduled_col="ktScheduledDate",
    fas_scheduled_col="fasScheduledDate"
):
    """
    Enterprise feature engineering using information that can be known
    during offboarding planning. Actual completion/outcome fields are not
    transformed into predictors.
    """

    df = data.copy()

    date_columns = [
        start_col,
        lwd_col,
        kt_scheduled_col,
        fas_scheduled_col
    ]

    for col in date_columns:
        if col in df.columns:
            df[col] = pd.to_datetime(df[col], errors="coerce")

    # --------------------------------------------------------
    # Calendar context from offboarding initiation
    # --------------------------------------------------------
    if start_col in df.columns:
        start = df[start_col]
        df["offboarding_start_year"] = start.dt.year
        df["offboarding_start_month"] = start.dt.month
        df["offboarding_start_quarter"] = start.dt.quarter
        df["offboarding_start_dayofweek"] = start.dt.dayofweek
        df["offboarding_start_dayofyear"] = start.dt.dayofyear
        df["offboarding_start_is_month_end"] = start.dt.is_month_end.astype("float")
        df["offboarding_start_is_quarter_end"] = start.dt.is_quarter_end.astype("float")

    # --------------------------------------------------------
    # Planned offboarding window
    # --------------------------------------------------------
    if start_col in df.columns and lwd_col in df.columns:
        df["planned_offboarding_days"] = (
            df[lwd_col] - df[start_col]
        ).dt.total_seconds() / 86400

    # --------------------------------------------------------
    # Notice-period planning features
    # --------------------------------------------------------
    if "noticePeriodDays" in df.columns:
        df["noticePeriodDays"] = pd.to_numeric(
            df["noticePeriodDays"], errors="coerce"
        )

    if "noticePeriodDays" in df.columns and "noticeServedDays" in df.columns:
        notice_period = pd.to_numeric(df["noticePeriodDays"], errors="coerce")
        notice_served = pd.to_numeric(df["noticeServedDays"], errors="coerce")
        df["notice_remaining_days"] = notice_period - notice_served
        df["notice_served_ratio"] = np.where(
            notice_period.abs() > np.finfo(float).eps,
            notice_served / notice_period,
            np.nan
        )

    # --------------------------------------------------------
    # KT scheduling / planning features
    # --------------------------------------------------------
    if start_col in df.columns and kt_scheduled_col in df.columns:
        df["kt_schedule_lead_days"] = (
            df[kt_scheduled_col] - df[start_col]
        ).dt.total_seconds() / 86400

    if lwd_col in df.columns and kt_scheduled_col in df.columns:
        df["kt_schedule_before_lwd_days"] = (
            df[lwd_col] - df[kt_scheduled_col]
        ).dt.total_seconds() / 86400

    # --------------------------------------------------------
    # F&F scheduling / planning feature
    # --------------------------------------------------------
    if start_col in df.columns and fas_scheduled_col in df.columns:
        df["fas_schedule_lead_days"] = (
            df[fas_scheduled_col] - df[start_col]
        ).dt.total_seconds() / 86400

    # --------------------------------------------------------
    # Process-planning indicators
    # --------------------------------------------------------
    if "ktRequiredFlag" in df.columns:
        df["kt_required_numeric"] = (
            df["ktRequiredFlag"].astype(str).str.strip().str.lower()
            .map({"true": 1, "yes": 1, "y": 1, "1": 1,
                  "false": 0, "no": 0, "n": 0, "0": 0})
        )

    if "ktRecipientSuccessorEmpId" in df.columns:
        df["successor_assigned"] = (
            df["ktRecipientSuccessorEmpId"].notna().astype(int)
        )

    # --------------------------------------------------------
    # Missingness is itself process information
    # --------------------------------------------------------
    useful_process_columns = [
        "ktRequiredFlag",
        "ktScheduledDate",
        "ktRecipientSuccessorEmpId",
        "fasScheduledDate",
        "lastWorkingDate",
        "noticePeriodDays",
        "noticeServedDays"
    ]

    for col in useful_process_columns:
        if col in df.columns:
            df[f"{col}_missing"] = df[col].isna().astype(int)

    return df


