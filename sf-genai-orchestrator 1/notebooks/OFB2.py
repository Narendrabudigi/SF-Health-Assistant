def _dynamic_tree_bounds(X):
    n_samples, n_features = X.shape

    sample_scale = max(
        float(np.sqrt(max(n_samples, 1))),
        1.0
    )

    feature_scale = max(
        float(np.sqrt(max(n_features, 1))),
        1.0
    )

    depth_high = max(
        2,
        int(np.ceil(np.log2(max(n_samples, 2))))
    )

    tree_low = max(
        2,
        int(np.ceil(sample_scale))
    )

    tree_high = max(
        tree_low + 1,
        int(np.ceil(
            sample_scale * feature_scale * 4
        ))
    )

    split_high = max(
        3,
        int(np.ceil(sample_scale))
    )

    leaf_high = max(
        2,
        int(np.ceil(
            sample_scale / feature_scale
        ))
    )

    return {
        "depth_high": depth_high,
        "tree_low": tree_low,
        "tree_high": tree_high,
        "split_high": split_high,
        "leaf_high": leaf_high
    }


