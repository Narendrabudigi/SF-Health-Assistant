# ============================================================

def regression_metrics_for_selection(
    y_true,
    pred
):

    denominator = np.where(
        np.abs(y_true) < np.finfo(float).eps,
        np.finfo(float).eps,
        np.abs(y_true)
    )

    mape = (
        np.mean(
            np.abs(
                (y_true - pred)
                / denominator
            )
        ) * 100
    )

    smape_den = (
        np.abs(y_true)
        + np.abs(pred)
    )

    valid = smape_den > 0

    smape = (
        np.mean(
            2 * np.abs(
                y_true[valid] -
                pred[valid]
            ) / smape_den[valid]
        ) * 100
        if valid.any()
        else np.nan
    )

    return {
        "R²": r2_score(
            y_true,
            pred
        ),

        "MAE": mean_absolute_error(
            y_true,
            pred
        ),

       "RMSE": np.sqrt(
    mean_squared_error(
        y_true,
        pred
    )
),

        "MAPE": mape,

        "sMAPE": smape
    }

