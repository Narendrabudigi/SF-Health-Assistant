def prepare_features(model_df, target_col, exclude_cols):
    data = model_df.copy().dropna(subset=[target_col])

    excluded = set(exclude_cols + [target_col])
    candidate_cols = [c for c in data.columns if c not in excluded]

    X = data[candidate_cols].copy()
    y = data[target_col].copy()

    # IDs, names and email are not useful generalizable predictors.
    identifier_patterns = [
        "offboardingId", "employeeId", "firstName", "lastName",
        "email", "activityId"
    ]
    X = X.drop(
        columns=[c for c in identifier_patterns if c in X.columns],
        errors="ignore"
    )

    # Raw datetimes are removed; date-derived features remain.
    raw_date_cols = [
        c for c in X.columns
        if pd.api.types.is_datetime64_any_dtype(X[c])
    ]
    X = X.drop(columns=raw_date_cols, errors="ignore")

    categorical_cols = X.select_dtypes(
        include=["object", "category", "string"]
    ).columns.tolist()
    numeric_cols = [c for c in X.columns if c not in categorical_cols]

    numeric_pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler())
    ])

    categorical_pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OrdinalEncoder(
            handle_unknown="use_encoded_value",
            unknown_value=-1
        )),
        ("scaler", StandardScaler())
    ])

    preprocessor = ColumnTransformer([
        ("num", numeric_pipe, numeric_cols),
        ("cat", categorical_pipe, categorical_cols)
    ])

    return X, y, preprocessor


def _regression_accuracy(y_true, pred):
    """Fraction of regression predictions within the configured tolerance."""
    y_true = np.asarray(y_true, dtype=float)
    pred = np.asarray(pred, dtype=float)
    finite = np.isfinite(y_true) & np.isfinite(pred)
    actual = y_true[finite]
    predicted = pred[finite]
    if not actual.size:
        return np.nan

    typical_magnitude = float(np.median(np.abs(actual)))
    tolerance = (
        np.maximum(np.abs(actual), typical_magnitude)
        * REGRESSION_ACCURACY_TOLERANCE_PCT / 100.0
    )
    return float(np.mean(np.abs(actual - predicted) <= tolerance))


def _regression_mape(y_true, pred):
    """MAPE in percent, omitting zero actuals where percentage error is undefined."""
    y_true = np.asarray(y_true, dtype=float)
    pred = np.asarray(pred, dtype=float)
    valid = np.isfinite(y_true) & np.isfinite(pred) & (y_true != 0)
    if not valid.any():
        return np.nan
    return float(np.mean(np.abs((y_true[valid] - pred[valid]) / y_true[valid])) * 100)


def regression_metrics(y_true, pred):
    y_true = np.asarray(y_true)
    pred = np.asarray(pred)

    mape = _regression_mape(y_true, pred)

    denom = np.abs(y_true) + np.abs(pred)
    valid = denom != 0
    smape = (
        np.mean(2 * np.abs(pred[valid] - y_true[valid]) / denom[valid]) * 100
        if valid.any() else np.nan
    )

    return {
        "R2": r2_score(y_true, pred),
        "MAE": mean_absolute_error(y_true, pred),
        "RMSE": np.sqrt(mean_squared_error(y_true, pred)),
        "MAPE": mape,
        "sMAPE": smape,
        "Accuracy": _regression_accuracy(y_true, pred),
        "Accuracy Tolerance %": REGRESSION_ACCURACY_TOLERANCE_PCT,
    }


def classification_metrics(y_true, prob, threshold=0.5):
    pred = (np.asarray(prob) >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(
        y_true, pred, labels=[0, 1]
    ).ravel()

    specificity = tn / (tn + fp) if (tn + fp) else np.nan

    return {
        "ROC-AUC": roc_auc_score(y_true, prob) if len(np.unique(y_true)) > 1 else np.nan,
        "PR-AUC": average_precision_score(y_true, prob) if len(np.unique(y_true)) > 1 else np.nan,
        "Accuracy": accuracy_score(y_true, pred),
        "Error Rate": 1 - accuracy_score(y_true, pred),
        "Precision": precision_score(y_true, pred, zero_division=0),
        "Recall": recall_score(y_true, pred, zero_division=0),
        "F1": f1_score(y_true, pred, zero_division=0),
        "Specificity": specificity,
        "Balanced Accuracy": balanced_accuracy_score(y_true, pred),
        "Brier Score": brier_score_loss(y_true, prob)
    }


def chronological_split(X, y, date_series, test_fraction=0.20):
    order = pd.to_datetime(date_series).sort_values().index
    X = X.loc[order]
    y = y.loc[order]

    cut = max(1, int(len(X) * (1 - test_fraction)))
    cut = min(cut, len(X) - 1)

    return (
        X.iloc[:cut], X.iloc[cut:],
        y.iloc[:cut], y.iloc[cut:]
    )


def make_tscv(n_samples, requested_splits=5):
    n_splits = min(requested_splits, max(2, n_samples // 5))
    if n_samples < 6:
        return None
    return TimeSeriesSplit(n_splits=n_splits)

