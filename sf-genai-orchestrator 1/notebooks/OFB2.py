def rca_top_contributors(summary, kpi):

    # --------------------------------------------------------
    # No contributors
    # --------------------------------------------------------

    if summary is None or summary.empty:

        return pd.DataFrame(columns=[
            "KPI",
            "Rank",
            "Factor",
            "Importance",
            "Contribution %",
            "Cause strength"
        ])

    # --------------------------------------------------------
    # Remove invalid / zero-contribution rows
    # --------------------------------------------------------

    x = summary.copy()

    if "Importance" in x.columns:

        x = x[
            x["Importance"].notna()
            &
            (x["Importance"] > 0)
        ].copy()

    elif "Contribution_%" in x.columns:

        x = x[
            x["Contribution_%"].notna()
            &
            (x["Contribution_%"] > 0)
        ].copy()

    # --------------------------------------------------------
    # If nothing remains
    # --------------------------------------------------------

    if x.empty:

        return pd.DataFrame(columns=[
            "KPI",
            "Rank",
            "Factor",
            "Importance",
            "Contribution %",
            "Cause strength"
        ])

    # --------------------------------------------------------
    # Sort by model-derived importance
    # --------------------------------------------------------

    x = x.sort_values(
        "Importance",
        ascending=False
    ).reset_index(drop=True)

    # --------------------------------------------------------
    # Dynamic number of contributors
    #
    # 3 or more -> Top 3
    # fewer than 3 -> all available
    # --------------------------------------------------------

    number_of_contributors = min(
        3,
        len(x)
    )

    x = x.head(
        number_of_contributors
    ).copy()

    # --------------------------------------------------------
    # Rank
    # --------------------------------------------------------

    x["Rank"] = np.arange(
        1,
        len(x) + 1
    )

    x["KPI"] = kpi

    # --------------------------------------------------------
    # Cause strength
    # --------------------------------------------------------

    if len(x) == 1:

        x["Cause strength"] = (
            "Model-derived root cause"
        )

    else:

        x["Cause strength"] = np.where(
            x["Rank"] == 1,
            "Strongest model-derived contributor",
            "Model-derived contributor"
        )

    # --------------------------------------------------------
    # Rename columns
    # --------------------------------------------------------

    x = x.rename(
        columns={
            "Feature": "Factor",
            "Contribution_%": "Contribution %"
        }
    )

    return x[[
        "KPI",
        "Rank",
        "Factor",
        "Importance",
        "Contribution %",
        "Cause strength"
    ]]


