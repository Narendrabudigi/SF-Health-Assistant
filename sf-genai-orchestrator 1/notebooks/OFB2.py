def _get_kpi_missing_config(kpi_name, required_fields):
    """Return only genuinely missing fields for this KPI."""
    missing_configurations = {
        "mandatory": [],
        "other": []
    }

    if (
        "configuration_report" not in globals()
        or configuration_report is None
        or configuration_report.empty
    ):
        config_rows = pd.DataFrame()
    else:
        config_rows = configuration_report[
            configuration_report["KPI"] == kpi_name
        ].copy()

    for field in required_fields:
        field_is_missing = field not in ofb.columns

        if not field_is_missing and not config_rows.empty:
            field_rows = config_rows[
                config_rows["Field"] == field
            ]
            if not field_rows.empty:
                field_is_missing = (
                    field_rows["Available"].fillna(0).eq(0).any()
                    or
                    field_rows["Status"].astype(str).str.upper().eq(
                        "FIELD MISSING"
                    ).any()
                )

        if not field_is_missing:
            continue

        info = FIELD_INFO.get(
            field,
            {"mandatory": "Not specified"}
        )

        missing_field = {
            "field": field
        }

        if str(info.get("mandatory", "Not specified")).strip().lower() == "yes":
            missing_configurations["mandatory"].append(missing_field)
        else:
            missing_configurations["other"].append(missing_field)

    return missing_configurations


def to_pascal_case(value):
    """Convert a metric label such as 'Offboarding Cycle Time' to PascalCase."""
    import re

    words = re.findall(r"[A-Za-z0-9]+", str(value))
    return "".join(word[:1].upper() + word[1:] for word in words)


