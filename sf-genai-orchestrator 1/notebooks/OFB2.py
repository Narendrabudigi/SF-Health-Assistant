def run_shap(result, title):
    if result is None:
        print(title, "— unavailable.")
        return None

    try:
        estimator = result["model"].named_steps["model"]
        prep = result["model"].named_steps["preprocess"]
        X = result["X_test"]
        if len(X) > SHAP_MAX_EXPLANATION_ROWS:
            X = X.sample(
                n=SHAP_MAX_EXPLANATION_ROWS,
                random_state=RANDOM_STATE,
            )

        Xt = prep.transform(X)
        Xt = Xt.toarray() if hasattr(Xt, "toarray") else np.asarray(Xt)
        names = np.asarray(prep.get_feature_names_out())

        if hasattr(estimator, "feature_importances_"):
            explainer = shap.TreeExplainer(estimator)
            values = explainer.shap_values(Xt)
        elif hasattr(estimator, "coef_"):
            explainer = shap.LinearExplainer(estimator, Xt)
            values = explainer.shap_values(Xt)
        else:
            explainer = shap.Explainer(estimator, Xt)
            values = explainer(Xt).values

        if isinstance(values, list):
            values = values[-1]
        if hasattr(values, "values"):
            values = values.values
        values = np.asarray(values)

        if values.ndim == 3:
            values = values[:, :, -1]

        mean_abs = np.nanmean(np.abs(values), axis=0)
        summary = pd.DataFrame({
            "Feature": names,
            "SHAP Importance": mean_abs
        }).sort_values(
            "SHAP Importance",
            ascending=False
        ).reset_index(drop=True)

        total = summary["SHAP Importance"].sum()
        summary["Contribution_%"] = (
            summary["SHAP Importance"] / total * 100
            if total > 0 else 0
        )

        return summary

    except Exception as e:
        print(title, "— SHAP unavailable:", e)
        return None


