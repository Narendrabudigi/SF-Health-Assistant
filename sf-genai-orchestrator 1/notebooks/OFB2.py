# This cell presents a single, consistent diagnostic rule
# for all selected models.
#
# It does not use arbitrary fixed performance thresholds.
# The selected model's own CV dispersion is used as the
# reference for generalization.

def model_status(
    train_score,
    test_score,
    gap,
    problem_type,
    cv_score=np.nan,
    cv_std=np.nan
):

    if any(
        pd.isna(v)
        for v in [
            train_score,
            test_score,
            cv_score
        ]
    ):
        return "Unknown"

    if pd.isna(cv_std):
        return "Unknown"

    train_cv_gap = (
        train_score - cv_score
    )

    test_cv_gap = (
        test_score - cv_score
    )

    # Strong overfitting evidence requires:
    # Train > CV beyond CV spread
    # AND
    # Test < CV beyond CV spread

    overfit_signal = (
        train_cv_gap > cv_std
        and
        (-test_cv_gap) > cv_std
    )

    if overfit_signal:
        return "Potential Overfitting"

    if test_cv_gap < -cv_std:
        return "Weak Generalization"

    return "No strong overfit signal"


