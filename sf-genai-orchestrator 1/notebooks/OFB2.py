def _specificity_score(estimator, X, y):

    pred = estimator.predict(X)

    tn, fp, _, _ = confusion_matrix(
        y,
        pred,
        labels=[0, 1]
    ).ravel()

    return (
        tn / (tn + fp)
        if (tn + fp)
        else np.nan
    )


def _brier_score(estimator, X, y):

    prob = estimator.predict_proba(X)[:, 1]

    return -brier_score_loss(
        y,
        prob
    )


