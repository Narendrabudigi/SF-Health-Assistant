def _round_json_numbers(value, digits=2):
    """Round floating-point values recursively without changing JSON structure."""
    if isinstance(value, bool):
        return value
    if isinstance(value, dict):
        return {key: _round_json_numbers(item, digits) for key, item in value.items()}
    if isinstance(value, list):
        return [_round_json_numbers(item, digits) for item in value]
    if isinstance(value, tuple):
        return [_round_json_numbers(item, digits) for item in value]
    # Handle Python floats plus NumPy floating scalar types (e.g. float32).
    try:
        import numbers
        if isinstance(value, numbers.Real) and not isinstance(value, numbers.Integral):
            return round(float(value), digits)
    except (TypeError, ValueError, OverflowError):
        pass
    return value


