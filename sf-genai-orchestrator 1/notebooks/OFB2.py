def native_feature_importance(result):
    if result is None:
        return None

    model = result["model"]
    prep = model.named_steps["preprocess"]
    estimator = model.named_steps["model"]
    feature_names = prep.get_feature_names_out()

    if hasattr(estimator, "feature_importances_"):
        values = np.abs(estimator.feature_importances_)
    elif hasattr(estimator, "coef_"):
        values = np.abs(np.ravel(estimator.coef_))
    else:
        return None

    summary = pd.DataFrame({
        "Feature": feature_names,
        "Importance": values
    }).sort_values("Importance", ascending=False).reset_index(drop=True)

    total = summary["Importance"].sum()
    summary["Contribution_%"] = summary["Importance"] / total * 100 if total > 0 else 0
    return summary


