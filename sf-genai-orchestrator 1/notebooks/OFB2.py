def cycle_health_and_variance(actual):
    if pd.isna(actual):
        return "Unknown", np.nan, np.nan

    if CYCLE_MIN_DAYS <= actual <= CYCLE_MAX_DAYS:
        return "Healthy", 0.0, 0.0

    if actual < 30:
        variance = actual - CYCLE_MIN_DAYS
        variance_pct = variance / CYCLE_MIN_DAYS * 100
    else:
        variance = actual - CYCLE_MAX_DAYS
        variance_pct = variance / CYCLE_MAX_DAYS * 100

    return "At-risk", variance, variance_pct

def rate_health_and_variance(actual, target):
    if pd.isna(actual):
        return "Unknown", np.nan, np.nan

    variance = actual - target
    variance_pct = variance / target * 100

    return (
        "Healthy" if actual >= target else "At-risk",
        variance,
        variance_pct
    )

