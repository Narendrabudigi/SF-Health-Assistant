def _apply_configured_field_aliases(frames):
    """Map incoming source column names onto this module's canonical names.

    Set OFB2_FIELD_ALIASES to a JSON object whose keys are canonical names
    and whose values are incoming names, for example:
    {"offboardingStartDate": "exitStartDate"}.
    """
    raw_aliases = _get_secret("OFB2_FIELD_ALIASES")
    if not raw_aliases:
        return frames

    try:
        aliases = json.loads(raw_aliases)
    except json.JSONDecodeError as exc:
        raise ValueError("OFB2_FIELD_ALIASES must be a JSON object") from exc

    if not isinstance(aliases, dict) or not all(
        isinstance(canonical, str) and isinstance(incoming, str)
        for canonical, incoming in aliases.items()
    ):
        raise ValueError(
            "OFB2_FIELD_ALIASES must map canonical column names to incoming names"
        )

    mapped_frames = []
    for frame in frames:
        rename = {
            incoming: canonical
            for canonical, incoming in aliases.items()
            if incoming in frame.columns and canonical not in frame.columns
        }
        mapped_frames.append(frame.rename(columns=rename))
    return mapped_frames


