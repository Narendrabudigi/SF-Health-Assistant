def tune_pipeline(
    pipe,
    params,
    X,
    y,
    task,
    cv,
    perform_tuning=False
):

    if (
        not perform_tuning
        or not params
        or cv is None
    ):

        pipe.fit(
            X,
            y
        )

        return (
            pipe,
            {},
            False
        )


    if task == "classification":

        scoring = {

            "roc_auc":
                "roc_auc",

            "pr_auc":
                "average_precision",

            "f1":
                "f1",

            "precision":
                "precision",

            "recall":
                "recall",

            "specificity":
                _specificity_score,

            "brier":
                _brier_score
        }


    else:

        scoring = {

            "r2":
                "r2",

            "mae":
                "neg_mean_absolute_error",

            "rmse":
                _neg_rmse,

            "mape":
                _neg_mape,

            "smape":
                _neg_smape
        }


    search = RandomizedSearchCV(

        estimator=pipe,

        param_distributions=params,

        n_iter=MODEL_TUNING_ITERATIONS,

        scoring=scoring,

        refit=_multi_metric_refit,

        cv=cv,

        random_state=RANDOM_STATE,

        n_jobs=-1,

        return_train_score=False
    )


    search.fit(
        X,
        y
    )


    return (
        search.best_estimator_,
        search.best_params_,
        True
    )


