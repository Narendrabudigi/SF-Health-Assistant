def _filter_to_standard_json_fields(value):
    """Keep the reference schema's top-level fields and remove added definition keys."""
    if isinstance(value, list):
        return [_filter_to_standard_json_fields(item) for item in value]
    if not isinstance(value, dict):
        return value
    # Represent a field-only missing-field entry as the field name itself.
    if set(value) == {"field"} and isinstance(value["field"], str):
        return value["field"]

    if "metricName" in value:
        allowed_fields = _STANDARD_METRIC_JSON_FIELDS
    elif "metrics" in value:
        allowed_fields = _STANDARD_JSON_ENVELOPE_FIELDS
    else:
        allowed_fields = None

    filtered = {}
    for key, item in value.items():
        if key == "definition":
            continue
        if allowed_fields is not None and key not in allowed_fields:
            continue
        filtered[key] = _filter_to_standard_json_fields(item)
    return filtered


