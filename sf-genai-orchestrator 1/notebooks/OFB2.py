def _json_safe_enhanced(value):
    """Convert pandas/numpy objects to JSON-safe Python values."""
    if isinstance(value, dict):
        return {str(k): _json_safe_enhanced(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe_enhanced(v) for v in value]
    if isinstance(value, np.ndarray):
        return [_json_safe_enhanced(v) for v in value.tolist()]
    if isinstance(value, pd.Series):
        return [_json_safe_enhanced(v) for v in value.tolist()]
    if isinstance(value, pd.DataFrame):
        return [_json_safe_enhanced(r) for r in value.to_dict(orient="records")]
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        value = float(value)
        return None if not np.isfinite(value) else value
    if isinstance(value, (pd.Timestamp, datetime)):
        return value.isoformat()
    if value is pd.NaT:
        return None
    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass
    return value


def _date_string(value):
    if value is None or pd.isna(value):
        return None
    try:
        return pd.Timestamp(value).date().isoformat()
    except Exception:
        return str(value)


def _period_label(ts, level):
    ts = pd.Timestamp(ts)
    if level == "monthly":
        return ts.strftime("%Y-%m")
    if level == "quarterly":
        return f"{ts.year}-Q{ts.quarter}"
    return str(ts.year)


def _hierarchical_trend(trend_dict):
    """Return Year -> Quarter -> Month trend structure."""
    monthly = pd.Series(trend_dict.get("monthly", pd.Series(dtype=float))).dropna()
    quarterly = pd.Series(trend_dict.get("quarterly", pd.Series(dtype=float))).dropna()
    yearly = pd.Series(trend_dict.get("yearly", pd.Series(dtype=float))).dropna()

    monthly.index = pd.to_datetime(monthly.index)
    quarterly.index = pd.to_datetime(quarterly.index)
    yearly.index = pd.to_datetime(yearly.index)

    now = pd.Timestamp.today().normalize()
    result = []

    for year, ygrp in monthly.groupby(monthly.index.year):
        yrow = {
            "period": str(year),
            "year": int(year),
            "average": float(yearly[yearly.index.year == year].iloc[-1])
                if (yearly.index.year == year).any() else float(ygrp.mean()),
            "isPartial": bool(year == now.year),
            "children": []
        }

        for q, qgrp in ygrp.groupby(ygrp.index.quarter):
            qmask = (quarterly.index.year == year) & (quarterly.index.quarter == q)
            qrow = {
                "period": f"{year}-Q{q}",
                "year": int(year),
                "quarter": int(q),
                "average": float(quarterly[qmask].iloc[-1])
                    if qmask.any() else float(qgrp.mean()),
                "isPartial": bool(year == now.year and q == now.quarter),
                "children": []
            }

            for month_ts, month_value in qgrp.sort_index().items():
                month_ts = pd.Timestamp(month_ts)
                qrow["children"].append({
                    "period": month_ts.strftime("%Y-%m"),
                    "year": int(month_ts.year),
                    "month": int(month_ts.month),
                    "average": float(month_value),
                    "isPartial": bool(
                        month_ts.year == now.year and
                        month_ts.month == now.month
                    )
                })

            yrow["children"].append(qrow)

        result.append(yrow)

    return result


def _trend_flat_fallback(trend_dict, level):
    series = pd.Series(trend_dict.get(level, pd.Series(dtype=float))).dropna()
    series.index = pd.to_datetime(series.index)
    now = pd.Timestamp.today().normalize()
    rows = []
    for ts, value in series.items():
        ts = pd.Timestamp(ts)
        row = {
            "period": _period_label(ts, level),
            "average": float(value),
            "isPartial": bool(
                ts.year == now.year and
                ((level == "monthly" and ts.month == now.month) or
                 (level == "quarterly" and ts.quarter == now.quarter) or
                 level == "yearly")
            )
        }
        if level == "monthly":
            row.update({"year": int(ts.year), "month": int(ts.month)})
        elif level == "quarterly":
            row.update({"year": int(ts.year), "quarter": int(ts.quarter)})
        else:
            row.update({"year": int(ts.year)})
        rows.append(row)
    return rows


def _trend_direction(trend_dict):
    monthly = pd.Series(trend_dict.get("monthly", pd.Series(dtype=float))).dropna().astype(float)
    if len(monthly) < 2:
        return "flat"
    first = float(monthly.iloc[0])
    last = float(monthly.iloc[-1])
    if last > first:
        return "up"
    if last < first:
        return "down"
    return "flat"


def _sample_style_trend_periods(trend_dict):
    """Build the sample JSON shape: yearly -> quarterly -> monthly children objects."""
    monthly = pd.Series(trend_dict.get("monthly", pd.Series(dtype=float))).dropna().astype(float)
    monthly.index = pd.to_datetime(monthly.index)
    if monthly.empty:
        return []

    yearly = pd.Series(trend_dict.get("yearly", pd.Series(dtype=float))).dropna().astype(float)
    quarterly = pd.Series(trend_dict.get("quarterly", pd.Series(dtype=float))).dropna().astype(float)
    yearly.index = pd.to_datetime(yearly.index)
    quarterly.index = pd.to_datetime(quarterly.index)

    now = pd.Timestamp.today().normalize()
    periods = []

    for year, ygrp in monthly.groupby(monthly.index.year):
        ymask = yearly.index.year == year
        yavg = float(yearly[ymask].iloc[-1]) if ymask.any() else float(ygrp.mean())
        yrow = {
            "period": str(year),
            "year": int(year),
            "average": yavg,
            "isPartial": bool(year == now.year),
            "children": {
                "granularity": "quarterly",
                "periods": []
            }
        }

        for quarter, qgrp in ygrp.groupby(ygrp.index.quarter):
            qmask = (quarterly.index.year == year) & (quarterly.index.quarter == quarter)
            qavg = float(quarterly[qmask].iloc[-1]) if qmask.any() else float(qgrp.mean())
            qrow = {
                "period": f"{year}-Q{quarter}",
                "quarter": int(quarter),
                "average": qavg,
                "isPartial": bool(year == now.year and quarter == now.quarter),
                "children": {
                    "granularity": "monthly",
                    "periods": []
                }
            }
            for ts, value in qgrp.sort_index().items():
                ts = pd.Timestamp(ts)
                qrow["children"]["periods"].append({
                    "period": ts.strftime("%Y-%m"),
                    "month": int(ts.month),
                    "average": float(value),
                    "isPartial": bool(ts.year == now.year and ts.month == now.month)
                })
            yrow["children"]["periods"].append(qrow)
        periods.append(yrow)

    return periods


def _forecast_series_enhanced(series, kpi_name):
    """Compare damped trend and HistGradientBoosting by rolling backtests."""
    from sklearn.ensemble import HistGradientBoostingRegressor

    s = pd.Series(series).dropna().astype(float)
    s.index = pd.to_datetime(s.index)

    if len(s) < MIN_TREND_POINTS:
        return {
            "nextMonth": None,
            "nextQuarter": None,
            "nextYear": None,
            "forecastModel": {
                "modelName": "Not available",
                "r2": None,
                "mae": None,
                "rmse": None,
                "mape": None,
                "accuracy": None,
                "accuracyTolerancePct": REGRESSION_ACCURACY_TOLERANCE_PCT,
                "rating": "not_assessed"
            }
        }

    recent = s.tail(TREND_WINDOW).reset_index(drop=True)

    def damped_fit_predict(train_values, horizon):
        model = Holt(
            np.asarray(train_values, dtype=float),
            damped_trend=True,
            initialization_method="estimated"
        )
        fitted_model = model.fit(optimized=True)
        return np.asarray(fitted_model.forecast(horizon), dtype=float), fitted_model

    def hist_gradient_fit_predict(train_values, horizon):
        values = np.asarray(train_values, dtype=float)
        x_train = np.arange(len(values), dtype=float).reshape(-1, 1)
        model = HistGradientBoostingRegressor(
            learning_rate=0.05,
            max_iter=100,
            max_leaf_nodes=min(7, max(2, len(values) // 2)),
            min_samples_leaf=max(1, min(5, len(values) // 2)),
            l2_regularization=1.0,
            random_state=RANDOM_STATE,
        )
        model.fit(x_train, values)
        x_future = np.arange(
            len(values), len(values) + horizon, dtype=float
        ).reshape(-1, 1)
        return np.asarray(model.predict(x_future), dtype=float), model

    # --------------------------------------------------------
    # Rolling one-step backtest for both forecast candidates.
    # --------------------------------------------------------
    backtests = {}
    candidate_methods = ("DampedTrend", "HistGradientBoosting")
    for method in candidate_methods:
        actuals, preds = [], []
        for i in range(MIN_TREND_POINTS, len(recent)):
            train = recent.iloc[:i].values
            try:
                if method == "DampedTrend":
                    pred, _ = damped_fit_predict(train, 1)
                else:
                    pred, _ = hist_gradient_fit_predict(train, 1)
                pred_value = float(pred[0])
                actuals.append(float(recent.iloc[i]))
                preds.append(pred_value)
            except Exception:
                continue

        if actuals:
            a = np.asarray(actuals, dtype=float)
            p = np.asarray(preds, dtype=float)
            mae = float(mean_absolute_error(a, p))
            rmse = float(np.sqrt(mean_squared_error(a, p)))
            accuracy = _regression_accuracy(a, p)
            mape = _regression_mape(a, p)
        else:
            mae = np.nan
            rmse = np.nan
            accuracy = np.nan
            mape = np.nan

        backtests[method] = {
            "mae": mae,
            "rmse": rmse,
            "accuracy": accuracy,
            "mape": mape,
        }

    candidates = [m for m, v in backtests.items() if pd.notna(v["rmse"])]
    if not candidates:
        selected_method = "DampedTrend"
    else:
        selected_method = min(
            candidates,
            key=lambda m: (
                backtests[m]["rmse"],
                backtests[m]["mae"] if pd.notna(backtests[m]["mae"]) else np.inf
            )
        )

    # --------------------------------------------------------
    # Fit the selected method on the complete recent window.
    # --------------------------------------------------------
    fitted_values = None
    forecasts = None
    methods_to_try = [selected_method] + [
        method for method in candidate_methods if method != selected_method
    ]
    for method in methods_to_try:
        try:
            if method == "DampedTrend":
                final_forecaster = Holt(
                    recent.values,
                    damped_trend=True,
                    initialization_method="estimated",
                ).fit(optimized=True)
                fitted_values = np.asarray(final_forecaster.fittedvalues, dtype=float)
                forecasts = np.asarray(final_forecaster.forecast(12), dtype=float)
            else:
                final_forecaster = HistGradientBoostingRegressor(
                    learning_rate=0.05,
                    max_iter=100,
                    max_leaf_nodes=min(7, max(2, len(recent) // 2)),
                    min_samples_leaf=max(1, min(5, len(recent) // 2)),
                    l2_regularization=1.0,
                    random_state=RANDOM_STATE,
                )
                x_recent = np.arange(len(recent), dtype=float).reshape(-1, 1)
                final_forecaster.fit(x_recent, recent.values)
                fitted_values = np.asarray(final_forecaster.predict(x_recent), dtype=float)
                x_future = np.arange(
                    len(recent), len(recent) + 12, dtype=float
                ).reshape(-1, 1)
                forecasts = np.asarray(final_forecaster.predict(x_future), dtype=float)
            selected_method = method
            break
        except Exception:
            fitted_values = None
            forecasts = None

    if fitted_values is None or forecasts is None:
        return {
            "nextMonth": None,
            "nextQuarter": None,
            "nextYear": None,
            "forecastModel": {
                "modelName": "Not available",
                "r2": None,
                "mae": None,
                "rmse": None,
                "mape": None,
                "accuracy": None,
                "accuracyTolerancePct": REGRESSION_ACCURACY_TOLERANCE_PCT,
                "rating": "not_assessed",
            },
        }

    trend_r2 = (
        float(r2_score(recent.values, fitted_values))
        if np.var(recent.values) > 0 else np.nan
    )
    bt_mae = backtests[selected_method]["mae"]
    bt_rmse = backtests[selected_method]["rmse"]

    # Analytical interval based on the selected method's historical
    # one-step-ahead backtest RMSE.
    margin = 1.96 * bt_rmse if pd.notna(bt_rmse) else np.nan

    def point_bounds(point):
        point = float(point)
        if pd.notna(margin):
            return point, point - margin, point + margin
        return point, np.nan, np.nan

    def forecast_health(value):
        if pd.isna(value):
            return "Unknown"
        if kpi_name == "Offboarding Cycle Time":
            return "Healthy" if CYCLE_MIN_DAYS <= value <= CYCLE_MAX_DAYS else "At-risk"
        if kpi_name == "Access & Asset Revocation Timeliness":
            return "Healthy" if value >= ACCESS_TARGET_PCT else "At-risk"
        if kpi_name == "Knowledge Transfer Completion Rate":
            return "Healthy" if value >= KT_TARGET_PCT else "At-risk"
        return "Unknown"

    last_month = pd.Timestamp(s.index.max()).to_period("M")
    next_month_period = last_month + 1
    next_quarter_period = pd.Period(str(last_month), freq="Q") + 1
    next_year_period = pd.Period(str(last_month), freq="Y") + 1

    m, ml, mu = point_bounds(forecasts[0])
    q, ql, qu = point_bounds(forecasts[2])
    y, yl, yu = point_bounds(forecasts[11])

    forecast_model = {
        "modelName": selected_method,
        "r2": trend_r2,
        "mae": bt_mae,
        "rmse": bt_rmse,
        "mape": backtests[selected_method]["mape"],
        "accuracy": backtests[selected_method]["accuracy"],
        "accuracyTolerancePct": REGRESSION_ACCURACY_TOLERANCE_PCT,
        "rating": _forecast_quality_rating(bt_rmse, recent.values)
    }

    return {
        "nextMonth": {
            "period": str(next_month_period),
            "predictedValue": m,
            "lowerBound": ml,
            "upperBound": mu,
            "predictedHealthState": forecast_health(m)
        },
        "nextQuarter": {
            "period": f"{next_quarter_period.year}-Q{next_quarter_period.quarter}",
            "predictedValue": q,
            "lowerBound": ql,
            "upperBound": qu,
            "predictedHealthState": forecast_health(q)
        },
        "nextYear": {
            "period": str(next_year_period),
            "predictedValue": y,
            "lowerBound": yl,
            "upperBound": yu,
            "predictedHealthState": forecast_health(y)
        },
        "forecastModel": forecast_model
    }


