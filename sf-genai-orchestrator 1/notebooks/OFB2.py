def _multi_metric_refit(cv_results):

    metric_columns = [
        c
        for c in cv_results
        if c.startswith("mean_test_")
    ]

    ranks = []

    for col in metric_columns:

        values = np.asarray(
            cv_results[col],
            dtype=float
        )

        if np.isfinite(values).any():

            ranks.append(
                pd.Series(values)
                .rank(
                    ascending=False,
                    method="average"
                )
                .to_numpy()
            )


    if not ranks:

        return int(
            np.nanargmax(
                cv_results[
                    metric_columns[0]
                ]
            )
        )


    mean_rank = np.nanmean(
        np.vstack(ranks),
        axis=0
    )

    return int(
        np.nanargmin(mean_rank)
    )


