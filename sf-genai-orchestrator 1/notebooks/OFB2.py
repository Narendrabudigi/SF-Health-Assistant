def _standard_text(value):
    if pd.isna(value):
        return ""

    return str(value).strip()


def _numeric_standard(value):
    """Extract a usable numeric SLA/target from an industry standard."""

    text = _standard_text(value).replace(",", "")

    if not text:
        return np.nan

    range_match = re.search(
        r"(\d+(?:\.\d+)?)\s*(?:to|-)\s*(\d+(?:\.\d+)?)",
        text,
        flags=re.I
    )

    if range_match:
        return float(range_match.group(2))

    number_match = re.search(
        r"\d+(?:\.\d+)?",
        text
    )

    return (
        float(number_match.group(0))
        if number_match
        else np.nan
    )


