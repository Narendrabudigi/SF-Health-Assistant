def field_coverage(data, field):
    total = len(data)

    if field not in data.columns:
        return {
            "Field": field,
            "Available": 0,
            "Total": total,
            "Missing": total,
            "Coverage %": 0.0,
            "Status": "FIELD MISSING"
        }

    available = int(data[field].notna().sum())
    missing = total - available
    coverage = available / total * 100 if total else np.nan

    if available == 0:
        status = "NO VALUES"
    elif available < total:
        status = "PARTIALLY AVAILABLE"
    else:
        status = "FULL COVERAGE"

    return {
        "Field": field,
        "Available": available,
        "Total": total,
        "Missing": missing,
        "Coverage %": coverage,
        "Status": status
    }


