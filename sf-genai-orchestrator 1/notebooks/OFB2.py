def _regression_quality_rating(r2_value):
    """Map held-out R² to the report's poor/fair/good rating vocabulary."""
    try:
        score = float(r2_value)
    except (TypeError, ValueError):
        return "not_assessed"
    if not np.isfinite(score):
        return "not_assessed"
    if score >= 0.70:
        return "good"
    if score >= 0.40:
        return "fair"
    return "poor"


def _classification_quality_rating(roc_auc):
    """Map held-out ROC-AUC to the report's poor/fair/good vocabulary."""
    try:
        score = float(roc_auc)
    except (TypeError, ValueError):
        return "not_assessed"
    if not np.isfinite(score):
        return "not_assessed"
    if score >= 0.80:
        return "good"
    if score >= 0.65:
        return "fair"
    return "poor"


def _forecast_quality_rating(rmse, observed_values):
    """Rate backtest RMSE relative to the typical observed KPI magnitude."""
    try:
        error = float(rmse)
        values = np.asarray(observed_values, dtype=float)
        scale = float(np.nanmean(np.abs(values)))
    except (TypeError, ValueError):
        return "not_assessed"
    if not np.isfinite(error) or not np.isfinite(scale):
        return "not_assessed"
    if scale <= np.finfo(float).eps:
        return "good" if error <= np.finfo(float).eps else "poor"
    relative_rmse = error / scale
    if relative_rmse <= 0.10:
        return "good"
    if relative_rmse <= 0.25:
        return "fair"
    return "poor"


def _rca_enhanced(rca_df, breach_value):
    if rca_df is None or not isinstance(rca_df, pd.DataFrame) or rca_df.empty:
        return {"applicable": False, "breachValue": breach_value, "factors": []}

    total_importance = pd.to_numeric(
        rca_df.get("Importance", pd.Series(dtype=float)), errors="coerce"
    ).fillna(0).sum()

    factors = []
    for _, row in rca_df.head(5).iterrows():
        importance = pd.to_numeric(row.get("Importance", np.nan), errors="coerce")
        contribution = pd.to_numeric(row.get("Contribution %", np.nan), errors="coerce")
        if pd.isna(contribution) and total_importance > 0 and pd.notna(importance):
            contribution = float(importance / total_importance * 100)

        factor_name = row.get("Factor", row.get("Feature", "Unknown"))
        factors.append({
            "rank": int(row.get("Rank", len(factors) + 1)),
            "factorName": factor_name,
            # Existing RCA is feature-level; no segment average is available
            # unless the existing RCA dataframe explicitly provides it.
            "segment": row.get("Segment", None),
            "avgFactorValue": row.get("Average", row.get("Mean", None)),
            "segmentAvgValue": row.get("Segment Average", None),
            "impactValue": importance,
            "impactPct": contribution
        })

    return {
        "applicable": True,
        "breachValue": breach_value,
        "factors": factors
    }


def _kpi_data_quality_enhanced(kpi, analysis_df, required_kpi_fields):
    total_records = int(len(analysis_df))
    missing_masks = []
    affected_missing = []
    affected_cells = 0
    for field in required_kpi_fields:
        mask = (
            analysis_df[field].isna()
            if field in analysis_df.columns
            else pd.Series(True, index=analysis_df.index)
        )
        missing_masks.append(mask)
        cell_count = int(mask.sum())
        affected_cells += cell_count
        if cell_count:
            affected_missing.append(field)

    missing_records = (
        int(pd.concat(missing_masks, axis=1).any(axis=1).sum())
        if missing_masks and total_records else 0
    )
    missing_pct = missing_records / total_records * 100 if total_records else np.nan

    invalid_pairs = {
        "Offboarding Cycle Time": [("offboardingCompletionDate", "offboardingStartDate")],
    }.get(kpi, [])
    invalid_masks = []
    affected_invalid = []
    for value_field, reference_field in invalid_pairs:
        if value_field in analysis_df.columns and reference_field in analysis_df.columns:
            mask = (
                analysis_df[value_field].notna()
                & analysis_df[reference_field].notna()
                & (analysis_df[value_field] < analysis_df[reference_field])
            )
            if mask.any():
                invalid_masks.append(mask)
                affected_invalid.append(value_field)
    invalid_records = (
        int(pd.concat(invalid_masks, axis=1).any(axis=1).sum())
        if invalid_masks else 0
    )

    unique_key = "offboardingId" if "offboardingId" in analysis_df.columns else None
    duplicate_records = (
        int((analysis_df[unique_key].notna() & analysis_df[unique_key].duplicated()).sum())
        if unique_key else 0
    )

    stale_kpi_names = {
        "Offboarding Cycle Time": {"Offboarding Cycle Time"},
        "Access & Asset Revocation Timeliness": {"Access & Asset Revocation"},
        "Knowledge Transfer Completion Rate": {"KT Timeliness"},
        "Full & Final Settlement Timeliness": {"Full & Final Settlement Timeliness"},
    }
    sr = pd.DataFrame()
    if (
        "staleness_record_report" in globals()
        and isinstance(staleness_record_report, pd.DataFrame)
        and not staleness_record_report.empty
    ):
        stale_names = stale_kpi_names.get(kpi, {kpi})
        sr = staleness_record_report[
            staleness_record_report["KPI"].isin(stale_names)
        ]
    stale_rows = (
        sr[sr["Staleness Status"].eq("POTENTIALLY STALE / INCOMPLETE")]
        if not sr.empty else pd.DataFrame()
    )
    stale_count = int(len(stale_rows))
    stale_fields = (
        stale_rows["Field"].dropna().astype(str).unique().tolist()
        if not stale_rows.empty else []
    )
    stale_dates = (
        pd.to_datetime(stale_rows["Business Event Date"], errors="coerce").dropna()
        if not stale_rows.empty else pd.Series(dtype="datetime64[ns]")
    )
    stale_range = (
        f"{_date_string(stale_dates.min())} to {_date_string(stale_dates.max())}"
        if not stale_dates.empty else None
    )

    checks = [
        {
            "checkName": "MissingValues",
            "category": "Completeness",
            "failedRecords": missing_records,
            "failedPct": missing_pct,
            "affectedColumns": affected_missing or None,
            "affectedCells": affected_cells,
        },
        {
            "checkName": "InvalidValues",
            "category": "Validity",
            "checkedRecords": total_records,
            "failedRecords": invalid_records,
            "failedPct": invalid_records / total_records * 100 if total_records else np.nan,
            "affectedColumns": affected_invalid or None,
        },
        {
            "checkName": "DuplicateRecords",
            "category": "Uniqueness",
            "checkedRecords": total_records,
            "failedRecords": duplicate_records,
            "failedPct": duplicate_records / total_records * 100 if total_records else np.nan,
            "affectedColumns": [unique_key] if duplicate_records and unique_key else None,
        },
        {
            "checkName": "Staleness",
            "category": "Staleness",
            "checkedRecords": total_records,
            "failedRecords": stale_count,
            "failedPct": stale_count / total_records * 100 if total_records else np.nan,
            "affectedColumns": stale_fields or None,
            "staleRange": stale_range,
        },
    ]

    if total_records == 0 or (required_kpi_fields and missing_records == total_records):
        overall = "poor"
    elif any(check["failedRecords"] > 0 for check in checks):
        overall = "fair"
    else:
        overall = "good"

    date_field = next(
        (field for field in ("offboardingStartDate", "lastWorkingDate") if field in analysis_df.columns),
        None,
    )
    period_dates = (
        pd.to_datetime(analysis_df[date_field], errors="coerce").dropna()
        if date_field else pd.Series(dtype="datetime64[ns]")
    )
    return {
        "overallRating": overall,
        "dataPeriod": {
            "from": _date_string(period_dates.min()) if not period_dates.empty else None,
            "to": _date_string(period_dates.max()) if not period_dates.empty else None,
        },
        "recordsAnalysed": total_records,
        "checks": checks,
    }


